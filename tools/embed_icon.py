"""The program's icon and its stopped-screen logo from their artwork (Pillow).

    python tools/embed_icon.py

Writes assets/livadix.ico (16 to 256 pixels; the Windows executable's icon,
tools/build.ps1 links it through the resource CMake generates),
src/app/livadix_icon.h (64 x 64 ARGB; the window icon on the other platforms,
where an executable has none) and src/app/livadix_logo.h (the landscape logo,
LOGO_WIDTH pixels wide, ARGB; what the window shows while no
Macintosh runs, desktop.c). Each artwork is cropped to what it draws; every
size is resampled with premultiplied alpha, so no dark fringe rings the edges.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets' / 'livadix-icon.png'
LOGO = ROOT / 'assets' / 'livadix-logo.png'
ICO = ROOT / 'assets' / 'livadix.ico'
HEADER = ROOT / 'src' / 'app' / 'livadix_icon.h'
LOGO_HEADER = ROOT / 'src' / 'app' / 'livadix_logo.h'
PREFIX = 'MC_ICON'
SIZES = [16, 20, 24, 32, 40, 48, 64, 128, 256]
WINDOW = 64
LOGO_WIDTH = 480


def cropped(path: Path) -> Image.Image:
    image = Image.open(path).convert('RGBA')
    # The drawing's extent: faint specks of the artwork's anti-aliasing do not count.
    return image.crop(image.getchannel('A').point(lambda a: 255 if a > 64 else 0).getbbox())


def square_logo() -> Image.Image:
    logo = cropped(SOURCE)
    side = max(logo.size)
    square = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    square.paste(logo, ((side - logo.width) // 2, (side - logo.height) // 2))
    return square


def resized(image: Image.Image, w: int, h: int) -> Image.Image:
    return image.convert('RGBa').resize((w, h), Image.Resampling.LANCZOS).convert('RGBA')


def argb(raw: bytes) -> list[int]:
    return [raw[at + 3] << 24 | raw[at] << 16 | raw[at + 1] << 8 | raw[at + 2] for at in range(0, len(raw), 4)]


def write_logo() -> str:
    logo = cropped(LOGO)
    height = round(logo.height * LOGO_WIDTH / logo.width)
    words = [f'0x{p:08x}u' for p in argb(resized(logo, LOGO_WIDTH, height).tobytes())]
    lines = [f'/* Generated by tools/embed_icon.py from {LOGO.relative_to(ROOT).as_posix()}. */',
             '#ifndef MC_LOGO_H', '#define MC_LOGO_H', f'#define MC_LOGO_WIDTH {LOGO_WIDTH}', f'#define MC_LOGO_HEIGHT {height}',
             'static const uint32_t MC_LOGO_ARGB[MC_LOGO_WIDTH * MC_LOGO_HEIGHT] = {']
    lines += [','.join(words[at:at + 8]) + ',' for at in range(0, len(words), 8)]
    lines += ['};', '#endif', '']
    LOGO_HEADER.write_text('\n'.join(lines), encoding='ascii', newline='\n')
    return f'{LOGO_HEADER.relative_to(ROOT).as_posix()}: {LOGO_WIDTH} x {height}'


def main() -> None:
    square = square_logo()
    frames = [resized(square, s, s) for s in SIZES]
    frames[-1].save(ICO, format='ICO', sizes=[(s, s) for s in SIZES], append_images=frames[:-1])
    words = [f'0x{p:08x}u' for p in argb(resized(square, WINDOW, WINDOW).tobytes())]
    lines = [f'/* Generated by tools/embed_icon.py from {SOURCE.relative_to(ROOT).as_posix()}. */',
             f'#ifndef {PREFIX}_H', f'#define {PREFIX}_H', f'#define {PREFIX}_SIZE {WINDOW}',
             f'static const uint32_t {PREFIX}_ARGB[{PREFIX}_SIZE * {PREFIX}_SIZE] = {{']
    lines += [','.join(words[at:at + 8]) + ',' for at in range(0, len(words), 8)]
    lines += ['};', '#endif', '']
    HEADER.write_text('\n'.join(lines), encoding='ascii', newline='\n')
    print(f'{ICO.relative_to(ROOT).as_posix()}: {", ".join(map(str, SIZES))}; '
          f'{HEADER.relative_to(ROOT).as_posix()}: {WINDOW} x {WINDOW}; {write_logo()}')


if __name__ == '__main__':
    main()
