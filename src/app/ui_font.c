/* The configuration window's two bitmap fonts, Livadix's own design: "Livadix System", a bold
 * 12-pixel face in the manner of a Platinum system font (two-pixel stems,
 * rounded rectangular bowls, cap height 9, x-height 7), and "Livadix Small", a
 * light 9-pixel face (one-pixel strokes, cap height 7, x-height 5). Each
 * glyph is its rows from the top row given ('#' set, '.' clear, rows split
 * by '/'); its width is the first row's length, and one blank column follows
 * it. Code points: printable ASCII, the en dash, bullet, ellipsis and the
 * curly quotes. */
