/* The fonts, decoded once into column bitmaps. */
typedef struct glyph { uint32_t code; uint8_t width; uint16_t rows[12]; } glyph;
struct ui_font {
    int height, ascent;
    size_t count;
    glyph glyphs[128];
};
static ui_font fonts[3];

static void decode(ui_font *f, const glyph_src *src, size_t n, int height, int ascent) {
    f->height = height;
    f->ascent = ascent;
    f->count = 0;
    for (size_t i = 0; i < n && f->count < sizeof f->glyphs / sizeof *f->glyphs; ++i) {
        glyph *g = &f->glyphs[f->count++];
        memset(g, 0, sizeof *g);
        g->code = src[i].code;
        const char *r = src[i].rows;
        g->width = (uint8_t)strcspn(r, "/");
        for (int row = src[i].top; *r && row < height; ++row) {
            for (int x = 0; *r && *r != '/'; ++x, ++r)
                if (*r == '#') g->rows[row] |= (uint16_t)(1u << x);
            if (*r == '/') r++;
        }
    }
}
const ui_font *ui_font_get(int which) {
    if (!fonts[0].count) {
        decode(&fonts[0], system12, sizeof system12 / sizeof *system12, 12, 10);
        decode(&fonts[1], small9, sizeof small9 / sizeof *small9, 9, 7);
        /* The small face in bold, as the Mac draws it: each glyph smeared one
         * pixel right, one column wider. */
        fonts[2] = fonts[1];
        for (size_t i = 0; i < fonts[2].count; ++i) {
            glyph *g = &fonts[2].glyphs[i];
            for (int row = 0; row < fonts[2].height; ++row) g->rows[row] |= (uint16_t)(g->rows[row] << 1);
            g->width++;
        }
    }
    return &fonts[which == UI_FONT_SMALL ? 1 : which == UI_FONT_SMALL_BOLD ? 2 : 0];
}
int ui_font_height(const ui_font *f) { return f->height; }
int ui_font_ascent(const ui_font *f) { return f->ascent; }

/* The next code point of UTF-8 text. */
static uint32_t next_code(const char **s) {
    const unsigned char *p = (const unsigned char *)*s;
    uint32_t c = *p++;
    if (c >= 0xF0 && (p[0] & 0xC0) == 0x80 && (p[1] & 0xC0) == 0x80 && (p[2] & 0xC0) == 0x80) {
        c = (c & 7) << 18 | (uint32_t)(p[0] & 63) << 12 | (uint32_t)(p[1] & 63) << 6 | (p[2] & 63); p += 3;
    } else if (c >= 0xE0 && (p[0] & 0xC0) == 0x80 && (p[1] & 0xC0) == 0x80) {
        c = (c & 15) << 12 | (uint32_t)(p[0] & 63) << 6 | (p[1] & 63); p += 2;
    } else if (c >= 0xC0 && (p[0] & 0xC0) == 0x80) {
        c = (c & 31) << 6 | (p[0] & 63); p += 1;
    }
    *s = (const char *)p;
    return c;
}
static const glyph *find_glyph(const ui_font *f, uint32_t code) {
    if (code >= 32 && code < 127 && code - 32 < f->count && f->glyphs[code - 32].code == code) return &f->glyphs[code - 32];
    for (size_t i = 0; i < f->count; ++i) if (f->glyphs[i].code == code) return &f->glyphs[i];
    return NULL;
}
/* An unknown character: a hollow box. */
static int box_width(const ui_font *f) { return f->height > 9 ? 6 : 4; }

int ui_text_width(const ui_font *f, const char *text) {
    int w = 0;
    while (*text) {
        const glyph *g = find_glyph(f, next_code(&text));
        w += (g ? g->width : box_width(f)) + 1;
    }
    return w ? w - 1 : 0;
}
int ui_text_width_n(const ui_font *f, const char *text, size_t bytes) {
    int w = 0;
    const char *end = text + bytes;
    while (*text && text < end) {
        const glyph *g = find_glyph(f, next_code(&text));
        w += (g ? g->width : box_width(f)) + 1;
    }
    return w ? w - 1 : 0;
}
int ui_draw_text(ui_canvas *c, const ui_font *f, int x, int y, const char *text, uint32_t color) {
    while (*text) {
        const glyph *g = find_glyph(f, next_code(&text));
        if (g) {
            for (int row = 0; row < f->height; ++row)
                for (int col = 0; col < g->width; ++col)
                    if (g->rows[row] >> col & 1) ui_pixel(c, x + col, y + row, color);
            x += g->width + 1;
        } else {
            const int w = box_width(f), top = f->height > 9 ? 2 : 1, bottom = f->ascent - 1;
            ui_frame(c, x, y + top, w, bottom - top + 1, color);
            x += w + 1;
        }
    }
    return x;
}
