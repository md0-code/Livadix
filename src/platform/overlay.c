#define GLYPH_W 6       /* 5 columns and a space */
#define GLYPH_H 8

int mc_text_width(const char *s) {
    return (int)strlen(s) * GLYPH_W;
}

static void put(uint32_t *fb, int w, int h, int x, int y, uint32_t c) {
    if (x >= 0 && y >= 0 && x < w && y < h) fb[(size_t)y * (size_t)w + (size_t)x] = c;
}

void mc_text_draw(uint32_t *fb, int w, int h, int x, int y, const char *s, uint32_t color) {
    for (; *s; s++, x += GLYPH_W) {
        int ch = toupper((unsigned char)*s);
        if (ch < 0x20 || ch > 0x5F) ch = '?';
        const uint8_t *g = FONT[ch - 0x20];
        for (int col = 0; col < 5; col++) {
            for (int row = 0; row < 7; row++) {
                if (g[col] >> row & 1) put(fb, w, h, x + col, y + row, color);
            }
        }
    }
}

void mc_panel(uint32_t *fb, int w, int h, int x, int y, int pw, int ph, uint32_t color, int alpha) {
    const uint32_t cr = color >> 16 & 0xFF, cg = color >> 8 & 0xFF, cb = color & 0xFF;
    for (int yy = y < 0 ? 0 : y; yy < y + ph && yy < h; yy++) {
        for (int xx = x < 0 ? 0 : x; xx < x + pw && xx < w; xx++) {
            uint32_t *p = &fb[(size_t)yy * (size_t)w + (size_t)xx];
            const uint32_t r = (*p >> 16 & 0xFF) * (uint32_t)(256 - alpha) / 256 + cr * (uint32_t)alpha / 256;
            const uint32_t g = (*p >> 8 & 0xFF) * (uint32_t)(256 - alpha) / 256 + cg * (uint32_t)alpha / 256;
            const uint32_t b = (*p & 0xFF) * (uint32_t)(256 - alpha) / 256 + cb * (uint32_t)alpha / 256;
            *p = 0xFF000000u | r << 16 | g << 8 | b;
        }
    }
}

void mc_osd_show(mc_osd *o, uint32_t now_ms, const char *fmt, ...) {
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(o->text, sizeof o->text, fmt, ap);
    va_end(ap);
    o->until_ms = now_ms + 2500;
}

void mc_osd_draw(const mc_osd *o, uint32_t now_ms, uint32_t *fb, int w, int h) {
    if (!o->text[0] || (int32_t)(o->until_ms - now_ms) <= 0) return;
    const int tw = mc_text_width(o->text);
    mc_panel(fb, w, h, 2, h - GLYPH_H - 6, tw + 6, GLYPH_H + 4, 0x000000, 180);
    mc_text_draw(fb, w, h, 5, h - GLYPH_H - 4, o->text, 0xFFFFFF60);
}
